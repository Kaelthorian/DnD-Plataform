const fs = require("fs");
const path = require("path");

const projectRoot = path.resolve(__dirname, "..");
const collectionPath = path.join(projectRoot, "node_modules", "@iconify-json", "game-icons", "icons.json");
const outputPath = path.join(
  projectRoot,
  "src",
  "app",
  "renderer",
  "dm-screen",
  "src",
  "components",
  "icons",
  "game-icon-data.js"
);

const selectedIcons = [
  "campfire",
  "castle",
  "crossed-swords",
  "dice-twenty-faces-twenty",
  "dragon-head",
  "hooded-assassin",
  "locked-chest",
  "magic-swirl",
  "open-treasure-chest",
  "potion-ball",
  "scroll-unfurled",
  "shield",
  "sleeping-bag",
  "spell-book",
  "treasure-map"
];

function toExportName(iconName) {
  return `${iconName.replace(/-([a-z])/g, (_match, letter) => letter.toUpperCase())}Icon`;
}

function main() {
  const collection = JSON.parse(fs.readFileSync(collectionPath, "utf8"));
  const missing = selectedIcons.filter((iconName) => !collection.icons?.[iconName]);
  if (missing.length) throw new Error(`Missing Game Icons: ${missing.join(", ")}`);

  const lines = [
    "// Generated by scripts/generate-dm-icon-data.js from @iconify-json/game-icons.",
    "// The curated objects keep the DM Screen offline and avoid bundling the full collection.",
    ""
  ];
  for (const iconName of selectedIcons) {
    const iconData = {
      ...collection.icons[iconName],
      width: collection.width || 512,
      height: collection.height || 512
    };
    lines.push(`export const ${toExportName(iconName)} = ${JSON.stringify(iconData)};`);
  }
  lines.push("");

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, lines.join("\n"), "utf8");
  console.log(`Wrote ${selectedIcons.length} curated Game Icons to ${path.relative(projectRoot, outputPath)}.`);
}

if (require.main === module) main();

module.exports = { selectedIcons, toExportName };
